// Sidebar artwork follows playback while selected Search videos retain priority.
import { readFileSync } from "node:fs";
import { open, check, calls, nav, submit, details, box, done } from "../harness.mjs";
const song = (title) => ({ path: `/home/u/Music/${title}.mp3`, title, artist: "Band", album_artist: "", album: "Album", track: null, disc: null, year: 2024, genre: "Rock", duration: 180, bitrate: 192, sample_rate: 44100, bit_depth: null, channels: 2, format: "MP3", size: 1000, modified: 1000, added: 1000, has_cover: true, loudness: -18 });
const [A, B, C] = ["Alpha", "Beta", "No cover"].map(song);
const config = JSON.parse(readFileSync(new URL("../../src-tauri/tauri.conf.json", import.meta.url)));
check("window: native minimum size is 720×576", config.app.windows[0].minWidth === 720 && config.app.windows[0].minHeight === 576);
const page = await open({ mock: { library: [A, B, C], noCover: [C.path] } });
const art = page.getByRole("complementary", { name: "Sidebar" }).getByLabel("Artwork");
const bar = page.getByRole("region", { name: "Music player", exact: true });
check("artwork: initial placeholder remains without a song or video", (await art.innerText()).includes("No video selected") && await art.locator("img").count() === 0);
await page.setViewportSize({ width: 720, height: 576 });
await nav(page, "Library").click();
await page.getByRole("button", { name: `Play ${A.title}`, exact: true }).click();
await art.locator(".album-art img").waitFor();
let first = await art.locator("img").getAttribute("src");
check("artwork: current song cover and title replace the placeholder", (await art.innerText()).includes(A.title) && first?.startsWith("blob:"));
check("artwork: album cover is shown without cropping", await art.locator("img").evaluate((el) => getComputedStyle(el).objectFit === "contain"));
await bar.getByRole("button", { name: "Pause", exact: true }).click();
check("artwork: pausing keeps the current album visible", await art.locator("img").getAttribute("src") === first);
await nav(page, "Search").click();
await submit(page, "https://www.youtube.com/watch?v=pasted00001");
await details(page).waitFor();
await page.waitForFunction(() => document.querySelector('.artwell .art:not(.album-art) img'));
check("artwork: a selected Search video takes priority over the album", await art.locator(".album-art").count() === 0 && (await art.locator("img").getAttribute("src")) !== first);
await nav(page, "Library").click();
await page.getByRole("button", { name: `Play ${B.title}`, exact: true }).click();
check("artwork: selected video keeps priority when playback changes", await art.locator(".album-art").count() === 0);
await nav(page, "Search").click();
await box(page).fill("");
await art.locator(".album-art img").waitFor();
check("artwork: clearing the video restores the current song", (await art.innerText()).includes(B.title));
await nav(page, "Library").click();
await page.getByRole("button", { name: `Play ${C.title}`, exact: true }).click();
await page.waitForFunction(() => document.querySelector('.artwell .cap')?.textContent.includes('No video selected'));
check("artwork: tracks without a cover restore the placeholder", await art.locator("img").count() === 0);
for (const name of ["Search", "Downloads", "History", "Library", "Settings"]) {
  await nav(page, name).click();
  check(`layout: ${name} fits 720×576 with a player`, await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth && document.documentElement.scrollHeight <= innerHeight));
}
check("layout: player controls stay within 720px", await bar.evaluate((el) => [...el.querySelectorAll('button')].filter((b) => b.getBoundingClientRect().width > 0).every((b) => { const r = b.getBoundingClientRect(); return r.left >= 0 && r.right <= innerWidth; })));
await nav(page, "Library").click();
await page.getByRole("button", { name: `Play ${A.title}`, exact: true }).click();
await art.locator(".album-art img").waitFor();
await page.screenshot({ path: "src-tauri/target/sidebar-album-720.png" });
check("artwork: cover fetch uses the shared cache", (await calls(page, "library_cover")).filter((c) => c.args.path === A.path).length === 1);
await bar.getByRole("button", { name: "Show the queue", exact: true }).click();
await page.getByRole("button", { name: "Clear queue", exact: true }).click();
await page.waitForFunction(() => document.querySelector('.artwell .cap')?.textContent.includes('No video selected'));
check("artwork: clearing the queue removes the previous album", await art.locator("img").count() === 0);
await done();
