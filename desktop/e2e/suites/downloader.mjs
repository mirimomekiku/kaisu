import { open, check, calls, nav, waitCalls, done, submit } from "../harness.mjs";

const saved = (id, url = `https://vimeo.com/${id}`) => ({ id, url, title: `Video ${id}`, thumbnail: "", preset: "audio", outDir: "/media/Music", extra: { audio_format: "mp3" }, status: "paused", progress: 0 });
const emit = (page, id, event) => page.evaluate(([id, event]) => {
  const control = window.__mock.downloadControls[id]; control.send(event);
  if (["done", "skipped", "error"].includes(event.kind)) control.resolve();
}, [id, event]);
const requests = async (page) => (await calls(page, "start_download")).map((call) => call.args.req);

let page = await open({ queue: [saved("one"), saved("two"), saved("three")], mock: { manualDownloads: true }, store: { mode: "advanced", concurrency: 3, globalRateLimit: "3M", fragmentBudget: 6, autoRetries: 2 } });
await nav(page, "Downloads").click();
await page.getByRole("button", { name: "Resume all", exact: true }).click();
await waitCalls(page, "start_download", 3);
let reqs = await requests(page);
check("budget: each queue slot reserves one third of the shared speed", reqs.every((r) => r.extra.rate_limit === "1048576"));
check("budget: combined fragment reservations stay inside the total", reqs.reduce((n, r) => n + r.extra.fragment_limit, 0) === 6);
check("retry: native requests use the application's coordinated retry policy", reqs.every((r) => r.extra.managed_retries === true));
const running = reqs[0];
await emit(page, running.id, { kind: "stalled", seconds: 35 });
await page.getByText(/No progress for 35s/).waitFor();
check("stall: the row explains stalled progress", true);
await emit(page, running.id, { kind: "stalled", seconds: 0 });
await emit(page, running.id, { kind: "progress", pct: 20, speed: 5000, eta: 30 });
await page.getByText(/No progress for 35s/).waitFor({ state: "detached" });
check("stall: progress recovery clears the notice", true);
await emit(page, running.id, { kind: "skipped", path: "/media/Music/existing.mp3" });
await page.getByText("Skipped existing", { exact: true }).waitFor();
check("collision: a verified existing output has an explicit skipped status", true);
await page.screenshot({ path: "src-tauri/target/downloader-budget.png" });
await nav(page, "Settings").click();
await page.getByLabel("Settings section", { exact: true }).selectOption("Downloads");
await page.getByLabel("Total download speed", { exact: true }).fill("2M");
await waitCalls(page, "cancel_download", 2);
await waitCalls(page, "start_download", 5);
reqs = await requests(page);
check("budget: changing the total restarts active jobs with the new share", reqs.slice(-2).every((r) => Number(r.extra.rate_limit) === Math.floor(2 * 1048576 / 3)));
await page.getByLabel("Download file conflicts").selectOption("skip");
await page.waitForFunction(() => JSON.parse(localStorage.getItem("__store")).settings.downloadConflict === "skip");
check("collision: the selected policy persists", true);
await page.context().close();

page = await open({ clock: true, queue: [saved("elsewhere", "https://vimeo.com/123"), saved("second", "https://www.youtube.com/watch?v=second00001"), saved("first", "https://youtu.be/first000001")], mock: { manualDownloads: true }, store: { mode: "advanced", concurrency: 1, autoRetries: 1 } });
await nav(page, "Downloads").click();
await page.getByRole("button", { name: "Resume all", exact: true }).click();
await waitCalls(page, "start_download", 1);
const initial = (await requests(page))[0];
await emit(page, initial.id, { kind: "error", message: "HTTP Error 429: Too Many Requests\nRetry-After: 120" });
await waitCalls(page, "start_download", 2);
check("cooldown: another website can use the available slot", (await requests(page))[1].url.startsWith("https://vimeo.com"));
check("cooldown: YouTube's short and full hosts share the notice", (await page.locator("main").innerText()).includes("Website cooldown"));
const unrelated = (await requests(page))[1];
await emit(page, unrelated.id, { kind: "done", path: "/media/Music/other.mp3" });
await page.clock.fastForward(119000); await page.waitForTimeout(100);
check("cooldown: Retry-After prevents early retries and new same-site jobs", (await requests(page)).length === 2);
await page.clock.runFor(2000);
await waitCalls(page, "start_download", 3);
check("cooldown: the queued retry resumes after the host deadline", (await requests(page))[2].url === initial.url);
await page.context().close();

page = await open({ queue: [{ ...saved("private", "https://cdn.example/video?token=signed-secret"), extra: { audio_format: "mp3", custom_args: '--add-headers "X-Token: header-secret"' } }], store: { mode: "advanced", customArgs: '--add-headers "Authorization: Bearer settings-secret"' }, mock: { manualDownloads: true } });
await page.waitForFunction(() => !localStorage.getItem("__store").includes("signed-secret") && !localStorage.getItem("__store").includes("header-secret") && !localStorage.getItem("__store").includes("settings-secret"));
check("secrets: legacy queue and settings credentials are migrated out of plaintext", true);
check("secrets: custom arguments use the operating system credential store", (await calls(page, "secret_set")).some((c) => c.args.name === "download-custom-args"));
check("secrets: private recovery is explicitly marked as needing fresh credentials", await page.evaluate(() => JSON.parse(localStorage.getItem("__store")).queue[0].extra.credentials_required === true));
await page.context().close();
page = await open({ mock: { manualDownloads: true }, store: { mode: "advanced", warnDuplicates: false } });
await submit(page, "https://youtu.be/abcdefghijk https://www.youtube.com/watch?v=abcdefghijk");
await page.getByRole("region", { name: "Selected videos" }).getByRole("button", { name: "Download 2 videos", exact: true }).waitFor();
await page.evaluate(() => {
  const button = [...document.querySelectorAll("button")].find((b) => b.textContent.trim() === "Download 2 videos");
  button.click(); button.click();
});
await waitCalls(page, "start_download", 1);
await page.waitForTimeout(200);
check("duplicates: a batch of URL aliases adds one artifact even during rapid concurrent submissions", (await requests(page)).length === 1);
await nav(page, "Downloads").click();
check("duplicates: only one queue row is created", await page.getByRole("button", { name: "Pause download", exact: true }).count() === 1);
await page.context().close();
await done();
