// Downloader lifecycle, late events, stages, original-choice recovery and destination preflight.
import { open, check, calls, nav, waitCalls, done } from "../harness.mjs";
const url = "https://vimeo.com/123456789";
const saved = { id: "saved-1", title: "Original video", url, thumbnail: "", preset: "audio", outDir: "/media/Music", extra: { audio_format: "flac" }, status: "downloading", progress: 20 };
const emit = (page, id, event) => page.evaluate(([id, event]) => window.__mock.downloadControls[id].send(event), [id, event]);
const request = async (page) => (await calls(page, "start_download")).at(-1).args.req;
let page = await open({ queue: [saved], mock: { manualDownloads: true }, store: { warnDuplicates: false, mode: "advanced" } });
await nav(page, "Downloads").click();
await page.getByRole("button", { name: "Resume download", exact: true }).click();
await waitCalls(page, "start_download", 1);
const first = await request(page);
check("attempts: native identity differs from persisted queue identity", first.id !== saved.id && first.recovery_id === saved.id);
check("stages: preparation is shown without a misleading percentage", (await page.locator("main").innerText()).includes("Preparing") && await page.getByRole("progressbar").getAttribute("aria-valuenow") === null);
await page.getByRole("button", { name: "Pause download", exact: true }).click();
await page.getByRole("button", { name: "Resume download", exact: true }).waitFor();
check("cancel: startup pause targets the current native attempt", (await calls(page, "cancel_download")).at(-1).args.id === first.id);
await page.getByRole("button", { name: "Resume download", exact: true }).click();
await waitCalls(page, "start_download", 2);
const second = await request(page);
await emit(page, first.id, { kind: "done", path: "/media/Music/stale.flac" });
check("attempts: late completion cannot finish a resumed job", second.id !== first.id && !(await page.locator("main").innerText()).includes("stale.flac") && await page.getByRole("button", { name: "Pause download", exact: true }).count() === 1);
await emit(page, second.id, { kind: "progress", pct: null, speed: 3000, eta: null });
check("progress: unknown size remains indeterminate", await page.getByRole("progressbar").getAttribute("aria-valuenow") === null);
for (const [stage, text] of [["converting", "Converting"], ["extras", "Adding extras"], ["verifying", "Verifying"]]) {
  await emit(page, second.id, { kind: "stage", stage });
  check(`stages: ${stage}`, (await page.locator("main").innerText()).includes(text));
}
await page.getByRole("button", { name: "Pause download", exact: true }).click();
await page.getByRole("button", { name: "Resume download", exact: true }).waitFor();
check("cancel: final verification can be paused", true);
await page.getByRole("button", { name: "Resume download", exact: true }).click();
await waitCalls(page, "start_download", 3);
const third = await request(page);
await emit(page, third.id, { kind: "done", path: null });
await page.getByRole("button", { name: "Try again", exact: true }).waitFor();
await page.getByRole("button", { name: saved.title, exact: true }).click();
check("completion: missing output is an error and creates no history entry", (await page.locator("main").innerText()).includes("without producing") && await page.evaluate(() => JSON.parse(localStorage.getItem("__store")).history.length) === 0);
await page.screenshot({ path: "src-tauri/target/downloader-error.png" });
await page.context().close();

const recovery = { id: "recover-1", request: { id: "old-attempt", recovery_id: "recover-1", url, preset: "audio", out_dir: "/media/Archive", extra: { audio_format: "flac", format_id: "251", output: { layout: "music" }, clip: { start: 5, end: 12, precise: true } } }, expected_path: "/media/Archive/Song.flac", resolved_format: "251", updated: 123 };
page = await open({ mock: { downloadRecovery: [recovery], manualDownloads: true } });
const notice = () => page.getByRole("region", { name: "Recover downloads", exact: true });
await notice().waitFor();
await page.screenshot({ path: "src-tauri/target/downloader-recovery.png" });
check("recovery: explains partial reuse and preserves the original destination for review", (await notice().innerText()).includes("may restart") && (await notice().innerText()).includes("/media/Archive"));
await notice().getByRole("button", { name: "Recover original downloads", exact: true }).click();
await waitCalls(page, "start_download", 1);
const restored = await request(page);
check("recovery: non-YouTube URL and exact choices survive", restored.url === url && restored.out_dir === "/media/Archive" && restored.extra.audio_format === "flac" && restored.extra.format_id === "251" && restored.extra.output.layout === "music" && restored.extra.clip.start === 5 && restored.recovery_id === "recover-1");
check("preflight: recovery checks its destination before starting", (await calls(page, "preflight_downloads")).at(-1).args.requests[0].out_dir === "/media/Archive");
await page.context().close();
page = await open({ mock: { downloadRecovery: [recovery], freeByFolder: { "/media/Archive": 50 } } });
await notice().waitFor();
await notice().getByRole("button", { name: "Recover original downloads", exact: true }).click();
await notice().getByRole("alert").waitFor();
check("preflight: low space on the actual recovery drive prevents launch", (await calls(page, "start_download")).length === 0);
await notice().getByRole("button", { name: "Discard recovery records", exact: true }).click();
await notice().waitFor({ state: "detached" });
check("recovery: discarding records keeps partial files", (await calls(page, "remove_leftovers")).length === 0 && (await calls(page, "discard_download_recovery")).length === 1);
await page.context().close();
page = await open({ queue: [saved, { ...saved, id: "bad", url: "https://" }, { ...saved, extra: { audio_format: "wav" } }], store: { mode: "advanced", concurrency: -100 } });
await nav(page, "Downloads").click();
check("restoration: corrupt and duplicate entries are skipped individually", await page.getByRole("button", { name: "Resume download", exact: true }).count() === 1);
await done();
