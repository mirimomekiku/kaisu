// Queue occurrence selection, bulk editing, drag, keyboard, undo and full-screen layout.
import { open, check, calls, chooseMenu, done } from "../harness.mjs";
const track = (title) => ({ path: `/music/${title}.mp3`, title, duration: 120 });
const A = track("Alpha"), B = track("Bravo"), C = track("Charlie"), D = track("Delta");
const page = await open({ data: { player: { queue: [A, B, A, C, D], index: 2, position: 12, volume: 1, rate: 1, repeat: "off", shuffle: false } }, mock: { audioSeconds: 120 } });
const bar = () => page.getByRole("region", { name: "Music player", exact: true });
const queue = () => page.getByRole("region", { name: "Play queue", exact: true });
const rows = () => queue().locator(".qp-row");
const order = () => rows().locator(".qp-title").allTextContents();
const selected = () => queue().locator(".qp-row[data-selected=true]").count();
await bar().waitFor();
await bar().getByRole("button", { name: "Play", exact: true }).click();
await bar().getByRole("button", { name: "Pause", exact: true }).waitFor();
await bar().getByRole("button", { name: "Show the queue", exact: true }).click();
check("occurrences: duplicate tracks have separate row identities", (await rows().evaluateAll((els) => new Set(els.map((el) => el.dataset.queueKey)).size)) === 5);
await queue().getByLabel("Select queued Alpha (1)", { exact: true }).check();
check("selection: selects one duplicate independently", await selected() === 1 && !(await queue().getByLabel("Select queued Alpha (3)", { exact: true }).isChecked()));
await rows().nth(3).locator(".qp-title").click({ modifiers: ["Shift"] });
check("selection: shift-click selects a range without playing it", await selected() === 4 && await rows().nth(2).getAttribute("aria-current") === "true");
await rows().nth(1).locator(".qp-title").click({ modifiers: ["Control"] });
check("selection: modifier-click toggles one entry", await selected() === 3);
await queue().getByRole("button", { name: "Deselect queued", exact: true }).click();
await queue().getByLabel("Select queued Bravo (2)", { exact: true }).check();
await queue().getByLabel("Select queued Charlie (4)", { exact: true }).check();
const currentSources = async () => (await calls(page, "play_in_app")).filter((c) => c.args.path === A.path).length;
const sources = await currentSources();
await chooseMenu(page, "Selected queue actions", "Move selected to top");
check("bulk move: keeps selected entries in queue order", JSON.stringify(await order()) === JSON.stringify(["Bravo", "Charlie", "Alpha", "Alpha", "Delta"]));
check("bulk move: current duplicate follows its entry", await rows().nth(3).getAttribute("aria-current") === "true");
await queue().getByRole("button", { name: "Undo queue edit", exact: true }).click();
check("undo: restores order and selection remains attached to entries", JSON.stringify(await order()) === JSON.stringify(["Alpha", "Bravo", "Alpha", "Charlie", "Delta"]) && await selected() === 2);
await rows().nth(1).dragTo(rows().nth(4));
check("drag: moves the selected block together", JSON.stringify(await order()) === JSON.stringify(["Alpha", "Alpha", "Delta", "Bravo", "Charlie"]));
await queue().getByRole("button", { name: "Undo queue edit", exact: true }).focus();
await page.keyboard.press("Control+z");
check("keyboard: undo restores a dragged block", JSON.stringify(await order()) === JSON.stringify(["Alpha", "Bravo", "Alpha", "Charlie", "Delta"]));
await chooseMenu(page, "Selected queue actions", "Remove selected from queue");
check("bulk remove: removes the entire selection once", await rows().count() === 3);
await queue().focus(); await page.keyboard.press("Control+z");
check("undo: restores all removed entries together", await rows().count() === 5);
check("playback: edits did not reload the current source", await currentSources() === sources && await bar().getByRole("button", { name: "Pause", exact: true }).count() === 1);
await rows().nth(1).focus(); await page.keyboard.press("Space"); await page.keyboard.press("Shift+ArrowDown");
check("keyboard: space selects and shift-arrow extends the range", await selected() === 2 && await rows().nth(2).evaluate((el) => el === document.activeElement));
await page.keyboard.press("Escape");
check("keyboard: escape clears selection", await selected() === 0);
await page.keyboard.press("Control+a"); await page.keyboard.press("Delete");
await page.locator(".queue-undo-notice").waitFor();
check("clear: removing all entries leaves an accessible undo", await bar().count() === 0 && await page.getByRole("button", { name: "Undo queue edit", exact: true }).isEnabled());
await page.getByRole("button", { name: "Undo queue edit", exact: true }).click();
await bar().waitFor();
check("restore: queue returns paused without fetching a source", await bar().getByRole("button", { name: "Play", exact: true }).count() === 1 && await currentSources() === sources);
await bar().getByRole("button", { name: "Show the queue", exact: true }).click();
await queue().getByRole("button", { name: "Clear queue", exact: true }).click();
await page.locator(".queue-undo-notice").waitFor();
await page.getByRole("button", { name: "Undo queue edit", exact: true }).focus(); await page.keyboard.press("Control+z");
check("clear: keyboard undo restores an explicitly cleared queue", await bar().count() === 1);
await bar().getByRole("button", { name: "Open full-screen player", exact: true }).click();
const full = page.getByRole("dialog", { name: "Full-screen player", exact: true });
await full.getByRole("tab", { name: /Up next/ }).click();
await queue().getByLabel("Select queued Alpha (1)", { exact: true }).check();
await page.keyboard.press("Escape");
check("full-screen: escape clears selection before closing", await full.count() === 1 && await selected() === 0);
await page.setViewportSize({ width: 760, height: 540 });
check("layout: queue fits the smallest window", await full.evaluate((el) => el.scrollWidth <= innerWidth && el.scrollHeight <= innerHeight));
await queue().getByRole("button", { name: "Clear queue", exact: true }).click();
await full.waitFor({ state: "detached" }); await page.locator(".queue-undo-notice").waitFor();
check("full-screen: clear exits and keeps undo accessible", await page.getByRole("button", { name: "Undo queue edit", exact: true }).isVisible());
await done();
