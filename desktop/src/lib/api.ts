import { Channel, invoke } from "@tauri-apps/api/core";

export type Preset = "best" | "p1080" | "p720" | "audio";
export type AudioFormat = "mp3" | "m4a" | "opus" | "flac" | "wav";
export type SponsorBlock = "off" | "mark" | "remove";
export type Browser = "firefox" | "chrome" | "chromium" | "edge" | "brave" | "opera" | "vivaldi";

export type Layout = "flat" | "channel" | "kind" | "year";
export type NameStyle = "title_id" | "title" | "channel_title" | "date_title";

export interface OutputOptions {
  layout: Layout;
  name: NameStyle;
  /** Replaces layout + name (Advanced). */
  custom: string | null;
  playlist_folder: boolean;
  playlist_numbering: boolean;
}

export interface PlaylistCtx {
  title: string;
  /** 1-based position in the playlist. */
  index: number;
  total: number;
}

export interface Clip {
  start: number;
  end: number;
  precise: boolean;
}

export interface SubtitleOptions {
  /** Language codes or patterns, like "en" or "en.*". */
  langs: string[];
  /** Put them inside the video file. */
  embed: boolean;
  /** Save them next to the video as .srt files. */
  file: boolean;
  /** Also take automatically generated captions when there are no human-made ones. */
  auto: boolean;
}

export interface SubtitleTrack {
  code: string;
  name: string;
  /** Generated by the site rather than written by a person. */
  auto: boolean;
}

export type SearchSource = "youtube" | "soundcloud";

export interface ExtraOptions {
  sponsorblock: SponsorBlock;
  cookies_from_browser: Browser | null;
  subs: SubtitleOptions | null;
  proxy: string | null;
  audio_format: AudioFormat;
  /** A specific yt-dlp format id (or `video+audio`); null lets the preset decide. */
  format_id: string | null;
  rate_limit: string | null;
  custom_args: string | null;
  verbose: boolean;
  output: OutputOptions;
  playlist: PlaylistCtx | null;
  clip: Clip | null;
}

export interface DownloadRequest {
  id: string;
  url: string;
  preset: Preset;
  out_dir: string;
  extra: ExtraOptions;
}

export type DownloadEvent =
  | { kind: "progress"; pct: number; speed: number | null; eta: number | null }
  | { kind: "processing" }
  | { kind: "meta"; title: string }
  | { kind: "log"; line: string }
  | { kind: "done"; path: string | null }
  | { kind: "cancelled" }
  | { kind: "error"; message: string };

export interface FormatInfo {
  id: string;
  ext: string;
  resolution: string | null;
  fps: number | null;
  vcodec: string | null;
  acodec: string | null;
  filesize: number | null;
  note: string | null;
  /** "video" = no audio track, "audio" = no video track, "both" = muxed. */
  kind: "video" | "audio" | "both";
}

export interface MediaInfo {
  title: string;
  thumbnail: string | null;
  uploader: string | null;
  duration_secs: number | null;
  view_count: number | null;
  like_count: number | null;
  /** `YYYYMMDD` */
  upload_date: string | null;
  description: string | null;
  webpage_url: string | null;
  is_live: boolean;
  subtitles: SubtitleTrack[];
  formats: FormatInfo[];
}

export interface SearchResult {
  id: string;
  title: string;
  url: string;
  channel: string | null;
  duration_secs: number | null;
  view_count: number | null;
  thumbnail: string;
  live: boolean;
}

export type ComponentId = "ytdlp" | "ffmpeg" | "js";

export interface Component {
  ready: boolean;
  source: "bundled" | "managed" | "system" | null;
  version: string | null;
  path: string | null;
}

export interface EngineInfo {
  ytdlp: Component;
  ffmpeg: Component;
  js: Component;
  ready: boolean;
}

export interface Platform {
  os: string;
  arch: string;
  distro: string | null;
  auto_install: boolean;
}

export interface SetupInfo {
  engine: EngineInfo;
  platform: Platform;
  manual_steps: string[];
  managed_dir: string;
}

export type SetupEvent =
  | { kind: "step"; component: ComponentId; label: string }
  | { kind: "progress"; component: ComponentId; pct: number }
  | { kind: "finished" };

export interface UpdateResult {
  updated: boolean;
  version: string;
  previous: string;
}

export const errorText = (e: unknown): string =>
  typeof e === "string" ? e : e instanceof Error ? e.message : "Something went wrong";

/** The proxy every request goes through (empty = none). Set from Settings; read by the wrappers below. */
let currentProxy: string | null = null;
export const setProxy = (proxy: string) => {
  currentProxy = proxy.trim() || null;
};

export const getMediaInfo = (url: string, cookiesFromBrowser: Browser | null) =>
  invoke<MediaInfo>("get_media_info", { url, cookiesFromBrowser, proxy: currentProxy });

export const searchMedia = (query: string, limit: number, source: SearchSource = "youtube") =>
  invoke<SearchResult[]>("search_media", { query, limit, source, proxy: currentProxy });

export const fileExists = (paths: string[]) => invoke<boolean[]>("file_exists", { paths });

export interface FileInfo {
  exists: boolean;
  size: number;
}
export const fileInfo = (paths: string[]) => invoke<FileInfo[]>("file_info", { paths });
/** Writes an exported history file the user chose in a save dialog (.csv or .json only). */
export const exportText = (path: string, contents: string) => invoke<void>("export_text", { path, contents });
export const openFile = (path: string) => invoke<void>("open_file", { path });
export const revealFile = (path: string) => invoke<void>("reveal_file", { path });
export const openUrl = (url: string) => invoke<void>("open_url", { url });
export const revealEngine = () => invoke<void>("reveal_engine");

export type LinkKind = "video" | "playlist" | "channel";

export interface PlaylistInfo {
  title: string;
  uploader: string | null;
  kind: LinkKind;
  total: number | null;
  entries: SearchResult[];
}

export type PowerAction = "sleep" | "shutdown";
export type CloseMode = "downloads" | "always" | "never";

export const classifyLink = (url: string) => invoke<LinkKind>("classify_link", { url });
export const getPlaylist = (url: string, limit: number) => invoke<PlaylistInfo>("get_playlist", { url, limit, proxy: currentProxy });
export const freeSpace = (path: string) => invoke<number>("free_space", { path });
export const openFolder = (path: string) => invoke<void>("open_folder", { path });
export const systemPower = (action: PowerAction) => invoke<void>("system_power", { action });
export const setTrayStatus = (active: number, queued: number, paused: number, mode: CloseMode) =>
  invoke<void>("set_tray_status", { active, queued, paused, mode });
export const trayAvailable = () => invoke<boolean>("tray_available");
export const quitApp = () => invoke<void>("quit_app");

export const getEngineInfo = () => invoke<EngineInfo>("get_engine_info");
export const updateEngine = () => invoke<UpdateResult>("update_engine", { proxy: currentProxy });
/** Tries the proxy with a real (tiny) request; resolves with a short message or rejects with the reason. */
export const testProxy = (proxy: string) => invoke<string>("test_proxy", { proxy });
export const defaultDownloadDir = () => invoke<string>("default_download_dir");
export const cancelDownload = (id: string) => invoke<void>("cancel_download", { id });

/** Starts a download; resolves when yt-dlp exits. Progress arrives through `onEvent`. */
export function startDownload(req: DownloadRequest, onEvent: (e: DownloadEvent) => void) {
  const channel = new Channel<DownloadEvent>();
  channel.onmessage = onEvent;
  return invoke<void>("start_download", { req, onEvent: channel });
}

export const checkSetup = () => invoke<SetupInfo>("check_setup");

/** Installs whatever is missing; resolves with the refreshed engine state. */
export function runSetup(onEvent: (e: SetupEvent) => void) {
  const channel = new Channel<SetupEvent>();
  channel.onmessage = onEvent;
  return invoke<EngineInfo>("run_setup", { onEvent: channel, proxy: currentProxy });
}
